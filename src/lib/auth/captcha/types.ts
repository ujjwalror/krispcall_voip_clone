/**
 * Phase 24D.SEC-6: Reusable CAPTCHA / Bot Defense Abstraction Types
 * Ephemeral browser memory only. NEVER persist tokens in storage or logs.
 */

export type AuthChallengeState =
  | 'IDLE'
  | 'LOADING'
  | 'READY'
  | 'VERIFIED'
  | 'EXPIRED'
  | 'ERROR';

export interface AuthChallengeWidgetRef {
  /** Resets the challenge widget and burns any local token reference */
  reset: () => void;
  /** Returns the current lifecycle state */
  getState: () => AuthChallengeState;
  /** Returns whether a verified token is currently held in ephemeral memory */
  hasToken: () => boolean;
}

export interface AuthChallengeWidgetProps {
  /** Invoked when a valid challenge token is generated by the provider */
  onVerify: (token: string) => void;
  /** Invoked when the challenge token expires (e.g. 300s TTL elapsed) */
  onExpire?: () => void;
  /** Invoked when the challenge widget encounters an error */
  onError?: (error: string) => void;
  /** Optional action binding for Turnstile (e.g. 'login', 'signup', 'recovery') */
  action?: string;
  /** Widget theme */
  theme?: 'light' | 'dark' | 'auto';
  /** Optional container class */
  className?: string;
  /** Whether the challenge is disabled / read-only */
  disabled?: boolean;
}
